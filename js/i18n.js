/*
  MailStone — interface localisation

  Three interface languages: English, Traditional Chinese, Simplified Chinese.

  Deliberate boundary: ONLY the interface is translated.
    - The generated email draft is ALWAYS English. It is the artefact the
      student sends, and its wording is the zero-hallucination baseline the
      project evaluates. Translating it would change the thing being measured.
    - Verbatim policy quotations are ALWAYS English. They are quoted word for
      word from official sources; a translation would no longer be verbatim
      and could not be checked against the clause number.
    - Student paraphrases, question wording, labels and explanations ARE
      translated, because those are what the student reads to decide.

  Implementation: a translation dictionary keyed by the exact (whitespace-
  normalised) English source string, plus a DOM text-node sweep. This avoids
  wrapping every assignment in t() and automatically covers HTML generated by
  innerHTML. Composite strings (counts, interpolated messages) are handled by
  t() at the call site with {n} placeholders.

  No persistence: language is held in memory and can be pinned with ?lang=.
  The app's privacy promise ("your answers are not saved") is unchanged.
*/

